// Regenerates the committed OpenAPI snapshot and its TypeScript types from a running backend.
// The backend's OpenApiSpecTests fails when the snapshot no longer matches the API.
import { writeFile } from "node:fs/promises";
import openapiTS, { astToString, type OpenAPI3 } from "openapi-typescript";

const url = process.env.API_DOCS_URL ?? "http://localhost:8080/v3/api-docs";

const response = await fetch(url).catch((cause: unknown) => {
  throw new Error(`Could not reach ${url}. Is the backend running with API_DOCS_ENABLED=true?`, {
    cause,
  });
});
if (!response.ok) {
  throw new Error(`GET ${url} returned ${String(response.status)}`);
}

const spec = (await response.json()) as OpenAPI3;
// The server URL depends on which host and port served the spec; without it the snapshot is stable
delete spec.servers;

await writeFile(new URL("../openapi.json", import.meta.url), `${JSON.stringify(spec, null, 2)}\n`);

const header = "// Generated by `pnpm gen:api` from openapi.json. Do not edit by hand.\n\n";
await writeFile(
  new URL("../src/schema.d.ts", import.meta.url),
  header + astToString(await openapiTS(spec)),
);

console.log(`Updated openapi.json and src/schema.d.ts from ${url}`);
